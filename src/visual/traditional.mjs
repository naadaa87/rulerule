const JC = { 초: '#2F7D4A', 한: '#C8323C' };
const jboard = (x, y, cell, cols = 9, rows = 10, o = {}) => {
  let s = rect(x - cell * 0.5, y - cell * 0.5, (cols - 1) * cell + cell, (rows - 1) * cell + cell, { fill: '#F1D9A8', stroke: C.ink, sw: 2, rx: 6 });
  let d = '';
  for (let c = 0; c < cols; c++) d += `M${x + c * cell} ${y}V${y + (rows - 1) * cell}`;
  for (let r = 0; r < rows; r++) d += `M${x} ${y + r * cell}H${x + (cols - 1) * cell}`;
  (o.palaces || []).forEach(([c0, r0]) => { d += `M${x + c0 * cell} ${y + r0 * cell}L${x + (c0 + 2) * cell} ${y + (r0 + 2) * cell}M${x + (c0 + 2) * cell} ${y + r0 * cell}L${x + c0 * cell} ${y + (r0 + 2) * cell}`; });
  return s + path(d, { stroke: '#8A6A3A', sw: 1.5 });
};
