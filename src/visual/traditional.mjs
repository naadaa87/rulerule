const YB = (x, y, S) => {
  const P = 0, L = S;
  const pts = {};
  const BR = [x + L, y + L], TR = [x + L, y], TL = [x, y], BL = [x, y + L], CC = [x + L / 2, y + L / 2];
  const lerp = (a, b, t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
  for (let k = 0; k <= 5; k++) { pts[k] = lerp(BR, TR, k / 5); pts[5 + k] = lerp(TR, TL, k / 5); pts[10 + k] = lerp(TL, BL, k / 5); pts[15 + k] = lerp(BL, BR, k / 5); }
  pts.d1 = lerp(TR, CC, 1 / 3); pts.d2 = lerp(TR, CC, 2 / 3); pts.d3 = lerp(TL, CC, 1 / 3); pts.d4 = lerp(TL, CC, 2 / 3);
  pts.d5 = lerp(CC, BL, 1 / 3); pts.d6 = lerp(CC, BL, 2 / 3); pts.d7 = lerp(CC, BR, 1 / 3); pts.d8 = lerp(CC, BR, 2 / 3); pts.c = CC;
  return pts;
};
